"""State and union-territory names in the regional languages of the tracked outlets.

The main alias table (entities.jsonl) holds English and Hindi names. Stories from Tamil, Bengali,
Marathi, Malayalam, Telugu and Kannada outlets name states in their own scripts, so their names are
fetched from Wikidata (labels and aliases of the state items) into config/entities/regional_states.yaml.
Only states are added: they are what the attention model counts.

Usage:
    python -m nazariya.entities.regional      # refresh config/entities/regional_states.yaml
"""

from __future__ import annotations

import json

import httpx
import yaml

from ..config import CONFIG

OUT = CONFIG / "entities" / "regional_states.yaml"
LANGS = ("ta", "bn", "mr", "ml", "te", "kn")
API = "https://www.wikidata.org/w/api.php"
UA = {"User-Agent": "NazariyaBot/0.1 (https://github.com/HalcyonVector/Nazariya)"}


def build() -> dict:
    ents = [json.loads(line) for line in (CONFIG / "entities" / "entities.jsonl").read_text(encoding="utf-8").splitlines() if line]
    qids = [e["qid"] for e in ents if e["type"] == "state"]
    out = {}
    with httpx.Client(headers=UA, timeout=60) as c:
        for i in range(0, len(qids), 40):
            r = c.get(API, params={"action": "wbgetentities", "ids": "|".join(qids[i:i + 40]),
                                   "props": "labels|aliases", "languages": "|".join(LANGS), "format": "json"})
            for qid, d in r.json()["entities"].items():
                names = {}
                for lang in LANGS:
                    vals = [d.get("labels", {}).get(lang, {}).get("value")]
                    vals += [a["value"] for a in d.get("aliases", {}).get(lang, [])]
                    vals = sorted({v for v in vals if v})
                    if vals:
                        names[lang] = vals
                out[qid] = names
    header = ("# Generated by `python -m nazariya.entities.regional` from Wikidata labels and aliases.\n"
              "# State and union-territory names in the regional languages, for the entity linker.\n")
    OUT.write_text(header + yaml.safe_dump({"states": out}, allow_unicode=True, sort_keys=True), encoding="utf-8")
    return out


if __name__ == "__main__":
    s = build()
    print(f"{len(s)} states; names per language:", {l: sum(l in v for v in s.values()) for l in LANGS})
