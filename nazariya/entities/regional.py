"""State, party and politician names in the regional languages of the tracked outlets.

The main alias table (entities.jsonl) holds English and Hindi names. Stories from Tamil, Bengali,
Marathi, Malayalam, Telugu and Kannada outlets name states, parties and people in their own scripts,
so those names are fetched from Wikidata (labels and aliases of the same items) into
config/entities/regional_states.yaml. The linker (nazariya/entities/linker.py) decides how each kind is
matched: states and parties by every name and by stem, people by full names only.

Usage:
    python -m nazariya.entities.regional      # refresh config/entities/regional_states.yaml
"""

from __future__ import annotations

import json

import httpx
import yaml

from ..config import CONFIG

OUT = CONFIG / "entities" / "regional_states.yaml"
LANGS = ("ta", "bn", "mr", "ml", "te", "kn")
API = "https://www.wikidata.org/w/api.php"
UA = {"User-Agent": "NazariyaBot/0.1 (https://github.com/HalcyonVector/Nazariya)"}


def _fetch(client: httpx.Client, qids: list[str]) -> dict:
    out = {}
    for i in range(0, len(qids), 40):
        r = client.get(API, params={"action": "wbgetentities", "ids": "|".join(qids[i:i + 40]),
                                    "props": "labels|aliases", "languages": "|".join(LANGS), "format": "json"})
        for qid, d in r.json()["entities"].items():
            names = {}
            for lang in LANGS:
                vals = [d.get("labels", {}).get(lang, {}).get("value")]
                vals += [a["value"] for a in d.get("aliases", {}).get(lang, [])]
                vals = sorted({v for v in vals if v})
                if vals:
                    names[lang] = vals
            if names:
                out[qid] = names
    return out


def build() -> dict:
    ents = [json.loads(line) for line in (CONFIG / "entities" / "entities.jsonl").read_text(encoding="utf-8").splitlines() if line]
    with httpx.Client(headers=UA, timeout=60) as c:
        out = {kind: _fetch(c, [e["qid"] for e in ents if e["type"] == kind]) for kind in ("state", "party", "person")}
    header = ("# Generated by `python -m nazariya.entities.regional` from Wikidata labels and aliases.\n"
              "# Names of states, parties and people in the regional languages, for the entity linker.\n")
    OUT.write_text(header + yaml.safe_dump({"states": out["state"], "parties": out["party"], "people": out["person"]},
                                           allow_unicode=True, sort_keys=True), encoding="utf-8")
    return out


if __name__ == "__main__":
    for kind, d in build().items():
        print(f"{kind}: {len(d)} with names;", {l: sum(l in v for v in d.values()) for l in LANGS})
