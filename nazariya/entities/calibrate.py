"""Calibrate single-word person names (surnames, one-word aliases) against the corpus.

A one-word name is only trustworthy if, in articles that contain it, the person is usually also
named in full somewhere. For "मोदी" that holds; for "गंभीर" (Gautam Gambhir, but also "serious")
or "पूजा" (Miss Pooja, but also "worship") it almost never does. For every single-word person
name with document frequency ≥ MIN_DF in recent articles:

    reliability = P(some candidate's full name appears | the word appears)

Names below MIN_RELIABILITY are written to config/entities/alias_calibration.yaml as dropped,
with their numbers, and the linker ignores them. Kept names are listed too, for review.

Usage:
    python -m nazariya.entities.calibrate            # → config/entities/alias_calibration.yaml
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from datetime import datetime, timedelta, timezone

import yaml
from sqlalchemy import select

from ..cluster import FINISHED
from ..config import CONFIG
from ..db import article_text, articles, get_engine
from .linker import MAX_ALIAS_TOKENS, Linker, normalise, tokenize

OUT = CONFIG / "entities" / "alias_calibration.yaml"
MIN_DF = 15
# 0.25 trades recall for precision: names like पायलट (Sachin Pilot / "pilot") or प्रधान
# (Dharmendra Pradhan / village head) sit around 0.13-0.22 and are mostly wrong matches.
MIN_RELIABILITY = 0.25
PERSON_TYPES = ("person", "foreign_person")


def corpus(days: int, limit: int) -> list[str]:
    since = datetime.now(timezone.utc) - timedelta(days=days)
    with get_engine().connect() as conn:
        rows = conn.execute(
            select(articles.c.title, articles.c.summary, article_text.c.text)
            .outerjoin(article_text, article_text.c.article_id == articles.c.id)
            .where(articles.c.status.in_(FINISHED), articles.c.published_at >= since)
            .order_by(articles.c.published_at.desc()).limit(limit)
        ).all()
    return [f"{r.title or ''}\n{r.text or r.summary or ''}" for r in rows]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=14)
    ap.add_argument("--limit", type=int, default=40000)
    args = ap.parse_args()

    raw = Linker(calibration_path=None)  # uncalibrated: every candidate name
    persons = {q for q, e in raw.entities.items() if e["type"] in PERSON_TYPES}
    single: dict[str, set[str]] = defaultdict(set)  # word → person qids it may name
    full: dict[tuple[str, ...], set[str]] = defaultdict(set)  # multi-word full names → person qids
    for key, entries in raw.index.items():
        for e in entries:
            if e.qid not in persons:
                continue
            if len(key) == 1:
                single[key[0]].add(e.qid)
            elif not e.derived:
                full[key].add(e.qid)

    docs = corpus(args.days, args.limit)
    print(f"{len(docs)} articles; {len(single)} single-word person names; {len(full)} full names")
    df: Counter = Counter()
    co: Counter = Counter()
    for text in docs:
        toks = [normalise(t) for t in tokenize(text)]
        present = set(toks) & single.keys()
        if not present:
            continue
        named = set()
        for i in range(len(toks)):
            for n in range(2, min(MAX_ALIAS_TOKENS, len(toks) - i) + 1):
                q = full.get(tuple(toks[i:i + n]))
                if q:
                    named |= q
        for w in present:
            df[w] += 1
            if single[w] & named:
                co[w] += 1

    dropped, kept = [], []
    for w, cands in sorted(single.items()):
        if df[w] < MIN_DF:
            continue
        rel = co[w] / df[w]
        for qid in sorted(cands):
            row = {"alias": w, "qid": qid, "label": raw.entities[qid]["label_en"], "df": df[w],
                   "with_full_name": co[w], "reliability": round(rel, 3)}
            (kept if rel >= MIN_RELIABILITY else dropped).append(row)
    dropped.sort(key=lambda r: -r["df"])
    kept.sort(key=lambda r: -r["df"])
    header = (
        "# Generated by `python -m nazariya.entities.calibrate`; do not edit by hand.\n"
        f"# Corpus: {len(docs)} recent articles. A single-word person name is dropped when it appears in\n"
        f"# ≥ {MIN_DF} articles but the person's full name co-occurs in < {MIN_RELIABILITY:.0%} of them.\n"
    )
    OUT.write_text(header + yaml.safe_dump({"dropped": dropped, "kept": kept}, allow_unicode=True,
                                           sort_keys=False, width=200), encoding="utf-8")
    print(f"dropped {len(dropped)}, kept {len(kept)} (others below df {MIN_DF}) → {OUT.relative_to(CONFIG.parent)}")
    for r in dropped[:15]:
        print(f"  drop {r['alias']:12s} {r['label']:28s} df={r['df']:5d} rel={r['reliability']:.2f}")
    for r in kept[:12]:
        print(f"  keep {r['alias']:12s} {r['label']:28s} df={r['df']:5d} rel={r['reliability']:.2f}")


if __name__ == "__main__":
    main()
